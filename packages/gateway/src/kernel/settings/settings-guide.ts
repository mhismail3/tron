import { durableAtomicWriteText } from "../../foundation/durable-json.js";
import { tronHomePath } from "../../foundation/tron-home-layout.js";
import { SECTIONS, type KeyDeclaration, type SettingsSchema } from "./settings-schema.js";

export function settingsGuidePath(tronHome: string): string {
  return tronHomePath(tronHome, "state/settings/guide.md");
}

const timing = (key: KeyDeclaration) => typeof key.timing === "string" ? key.timing : `widen ${key.timing.widen}, narrow ${key.timing.narrow}`;

function keyLines(key: KeyDeclaration): string[] {
  const layers = Object.keys(key.layers).join(", ");
  return [
    `### \`${key.id}\`: ${key.label}`, "",
    key.help, "",
    `- Layers: ${layers}${key.qualifier ? `; qualifier \`${key.qualifier}\`` : ""}`,
    `- Writers: ${key.writers.join(", ")}`,
    `- Takes effect: ${timing(key)}, ${key.effect}`,
    `- Native tap: ${key.tap ? `${key.tap}${key.tap === "install" || key.tap === "irreversible" ? "" : " (widening only)"}` : "none"}`,
    ...(key.confirm ? [`- Card: ${key.confirm}`] : []),
    ...(key.entry ? [`- Value: ${key.entry.hint} Example: \`${key.entry.example}\``] : []),
    "",
  ];
}

function renderSettingsGuide(schema: SettingsSchema): string {
  const lines = [
    "# Tron settings guide", "",
    "Generated by the Gateway from its settings schema at start. Change settings only with the `settings` tool:",
    "`resolve` reads values and layers, `change` applies a typed edit (add `dryRun` to preview), `history` pages the audit,",
    "`undo` and `applyAgain` act on a `changeId` from history, `inventory` lists hooks, packages, modules, MCP servers and",
    "custom providers, and `update` (Home only) installs one exact package version. A change that widens trust, privacy",
    "or spend, or installs, shows the native card and applies only on its tap.", "",
  ];
  for (const section of [...SECTIONS].sort((left, right) => left.order - right.order)) {
    const keys = schema.KEYS.filter(key => key.group === section.id).sort((left, right) => left.order - right.order);
    if (!keys.length) continue;
    lines.push(`## ${section.title}`, "", section.description, "", ...keys.flatMap(keyLines));
  }
  lines.push("## Records", "", "Changed one instance at a time through `change`, named by their qualifier.", "");
  for (const subject of schema.RECORD_SUBJECTS) {
    const record = schema.recordKey(subject.id);
    lines.push(...(record ? keyLines({ ...record, label: subject.label }) : [`### \`${subject.id}\`: ${subject.label}`, "", "Read only.", ""]));
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export function writeSettingsGuide(tronHome: string, schema: SettingsSchema): Promise<void> {
  return durableAtomicWriteText(settingsGuidePath(tronHome), renderSettingsGuide(schema));
}
