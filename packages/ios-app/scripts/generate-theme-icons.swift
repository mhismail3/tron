import Foundation

/// Compile together with ThemeColor.swift: the app palette is the only mapping.
/// AppIcon.icon owns the silhouette, placement, background and glass materials.
@main
struct GenerateThemeIcons {
    static func main() throws {
        let root = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
        let icons = root.appendingPathComponent("Sources/Icons", isDirectory: true)
        let primary = icons.appendingPathComponent("AppIcon.icon", isDirectory: true)
        let template = try Data(contentsOf: primary.appendingPathComponent("icon.json"))
        let mask = try Data(contentsOf: primary.appendingPathComponent("Assets/tron-mark.png"))
        let fileManager = FileManager.default
        for theme in ThemeColor.allCases {
            var icon = try JSONSerialization.jsonObject(with: template) as! [String: Any]
            var groups = icon["groups"] as! [[String: Any]]
            var layers = groups[0]["layers"] as! [[String: Any]]
            layers[0]["fill-specializations"] = [
                ["value": ["solid": srgb(theme.lightHex)]],
                ["appearance": "dark", "value": ["solid": srgb(theme.darkHex)]],
                ["appearance": "tinted", "value": ["solid": "extended-gray:1.00000,1.00000"]]
            ]
            groups[0]["layers"] = layers
            icon["groups"] = groups
            let target = icons.appendingPathComponent("\(theme.appIconName).icon", isDirectory: true)
            try fileManager.createDirectory(at: target.appendingPathComponent("Assets"), withIntermediateDirectories: true)
            var data = try JSONSerialization.data(withJSONObject: icon, options: [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes])
            data.append(0x0A)
            try data.write(to: target.appendingPathComponent("icon.json"), options: .atomic)
            try mask.write(to: target.appendingPathComponent("Assets/tron-mark.png"), options: .atomic)
            print("\(theme.label): \(theme.appIconName), \(theme.lightHex) / \(theme.darkHex)")
        }
        let names = ThemeColor.allCases.map(\.appIconName).joined(separator: " ")
        let config = "// Generated by generate-theme-icons.sh from ThemeColor.swift.\nASSETCATALOG_COMPILER_ALTERNATE_APPICON_NAMES = \(names)\n"
        try Data(config.utf8).write(to: root.appendingPathComponent("Configuration/ThemeIcons.xcconfig"), options: .atomic)
    }

    private static func srgb(_ hex: String) -> String {
        let value = UInt32(hex.dropFirst(), radix: 16)!
        let channels = [16, 8, 0].map { Double((value >> $0) & 255) / 255 }
        return "srgb:" + channels.map { String(format: "%.5f", locale: Locale(identifier: "en_US_POSIX"), $0) }.joined(separator: ",") + ",1.00000"
    }
}
