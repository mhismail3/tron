#!/bin/bash
# Purpose: install (bootstrap) or check (doctor) the pinned Dafny proof toolchain (dafny.pin), user-local, no sudo.
# Usage: scripts/tron proof bootstrap|doctor
# The install lives in one per-user cache shared by every worktree, outside ~/.tron:
#   ${XDG_CACHE_HOME:-$HOME/Library/Caches}/tron-proof/{dafny-<ver>/,bin/dafny,bin/z3,cache/}
# Every run re-verifies the installed tree against the pin, so a shared cache cannot drift; any mismatch is fatal.
# bootstrap downloads and installs only when the tree is absent; doctor never writes.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
set -a; source "$HERE/dafny.pin"; set +a
MODE="${1:-}"
case "$MODE" in bootstrap|doctor) ;; *) echo "usage: scripts/tron proof bootstrap|doctor" >&2; exit 64 ;; esac
PREFIX="${XDG_CACHE_HOME:-$HOME/Library/Caches}/tron-proof"
DEST="$PREFIX/dafny-$DAFNY_VERSION"; ZIP="$PREFIX/cache/$(basename "$DAFNY_URL")"
die() { echo "proof $MODE: FAIL: $*" >&2; exit 1; }
sha() { shasum -a 256 "$1" | cut -c1-64; }
tree_sha() { (cd "$1" && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 shasum -a 256 | shasum -a 256 | cut -c1-64); }
[ "$(uname -sm)" = "Darwin arm64" ] || die "pin is for Darwin arm64, host is $(uname -sm)"

# The only entry point callers use: the pinned binary, telemetry off, default (bundled) solver.
wrapper() {
  echo '#!/bin/bash'
  echo "# Generated by tools/proof/bootstrap.sh: pinned Dafny $DAFNY_VERSION, bundled .NET and Z3 $Z3_VERSION."
  echo "DAFNY_BIN='$DEST/dafny'"
  cat <<'SH'
export DOTNET_CLI_TELEMETRY_OPTOUT=1 DOTNET_NOLOGO=1
# Solver parallelism cap (shared Mac): each verifying command uses DAFNY_CORES Z3 processes (default 1)
# unless the caller passes --cores itself. Callers that run several commands at once bound their own jobs.
case " $* " in
  *" --cores"*) ;;
  *)
    case "${1:-}" in
      verify|build|run|test) set -- "$1" --cores "${DAFNY_CORES:-1}" "${@:2}" ;;
      # translate takes its target language first: `dafny translate js --cores 1 ...`.
      translate) set -- "$1" "${2:-}" --cores "${DAFNY_CORES:-1}" "${@:3}" ;;
    esac ;;
esac
exec "$DAFNY_BIN" "$@"
SH
}

if [ "$MODE" = bootstrap ]; then
  # One installer at a time per cache: worktrees share it.
  if [ -z "${TRON_PROOF_INSTALL_LOCKED:-}" ]; then
    mkdir -p "$PREFIX"
    TRON_PROOF_INSTALL_LOCKED=1 exec /usr/bin/lockf -k "$PREFIX/.install.lock" /bin/bash "$0" "$@"
  fi
  if [ ! -d "$DEST" ]; then
    mkdir -p "$PREFIX/cache"
    if [ ! -f "$ZIP" ] || [ "$(sha "$ZIP")" != "$DAFNY_ZIP_SHA256" ]; then
      echo "proof bootstrap: downloading $DAFNY_URL"
      curl -fsSL --retry 3 -o "$ZIP.part" "$DAFNY_URL"; mv "$ZIP.part" "$ZIP"
    fi
    [ "$(sha "$ZIP")" = "$DAFNY_ZIP_SHA256" ] || die "archive sha256 $(sha "$ZIP") != pinned $DAFNY_ZIP_SHA256"
    echo "proof bootstrap: archive sha256 OK ($DAFNY_ZIP_SHA256)"
    STAGE="$(mktemp -d "$PREFIX/.stage.XXXXXX")"; trap 'rm -rf "$STAGE"' EXIT
    unzip -q "$ZIP" -d "$STAGE"
    mv "$STAGE/dafny" "$DEST"
  fi
else
  [ -d "$DEST" ] || die "pinned Dafny missing at $DEST (run: scripts/tron proof bootstrap)"
fi

# Verify the installed tree every time (catches partial extraction and later tampering).
[ "$(tree_sha "$DEST")" = "$DAFNY_TREE_SHA256" ] || die "tree digest mismatch in $DEST (remove it and run: scripts/tron proof bootstrap)"
[ "$(find "$DEST" -type f | wc -l | tr -d ' ')" = "$DAFNY_TREE_FILES" ] || die "file count mismatch in $DEST"
for pair in "z3/bin/z3-$Z3_VERSION:$Z3_SHA256" "z3/bin/z3-$Z3_ALT_VERSION:$Z3_ALT_SHA256" \
            "libcoreclr.dylib:$DOTNET_CORECLR_SHA256" "System.Private.CoreLib.dll:$DOTNET_CORELIB_SHA256" \
            "dafny:$DAFNY_HOST_SHA256" "Dafny.dll:$DAFNY_DLL_SHA256" "DafnyPrelude.bpl:$DAFNY_PRELUDE_SHA256"; do
  [ "$(sha "$DEST/${pair%%:*}")" = "${pair#*:}" ] || die "digest mismatch: ${pair%%:*}"
done
grep -q "\"version\": \"${DOTNET_RUNTIME#* }\"" "$DEST/Dafny.runtimeconfig.json" || die ".NET runtime is not $DOTNET_RUNTIME"

if [ "$MODE" = bootstrap ]; then
  mkdir -p "$PREFIX/bin"
  wrapper > "$PREFIX/bin/.dafny.part"; chmod +x "$PREFIX/bin/.dafny.part"; mv "$PREFIX/bin/.dafny.part" "$PREFIX/bin/dafny"
  ln -sfn "$DEST/z3/bin/z3-$Z3_VERSION" "$PREFIX/bin/z3"
else
  [ -x "$PREFIX/bin/dafny" ] && cmp -s <(wrapper) "$PREFIX/bin/dafny" || die "entry point $PREFIX/bin/dafny is missing or not the pinned wrapper (run: scripts/tron proof bootstrap)"
  [ "$(readlink "$PREFIX/bin/z3")" = "$DEST/z3/bin/z3-$Z3_VERSION" ] || die "$PREFIX/bin/z3 is not the pinned Z3 (run: scripts/tron proof bootstrap)"
fi

# Self-check: versions reported by the binaries equal the pin.
v="$("$PREFIX/bin/dafny" --version)"; [ "$v" = "$DAFNY_VERSION+$DAFNY_COMMIT" ] || die "dafny reports $v"
z="$("$PREFIX/bin/z3" --version)"; [ "$z" = "Z3 version $Z3_VERSION - 64 bit" ] || die "z3 reports $z"
echo "proof $MODE: dafny $v, $DOTNET_RUNTIME (bundled), Z3 $Z3_VERSION; tree sha256 OK ($DAFNY_TREE_FILES files)"
echo "proof $MODE: OK -> $PREFIX/bin/dafny"
